"""2026-only Week 6 target share rebuild. No blanket caps or prior-season shares.
Requires historical CSV generated by build_week6_historical_targets.py.
Writes a separate review CSV; never overwrites original projections.
"""
from pathlib import Path
import pandas as pd
import numpy as np

ROOT=Path("data/projections")
source=ROOT/"2026_week6_league_v4_full.csv"
history=ROOT/"2026_week6_historical_target_shares.csv"
output=ROOT/"2026_week6_2026_target_share_review.csv"
if not history.exists(): raise SystemExit("Missing 2026 historical weekly targets; run import first")
p=pd.read_csv(source)
h=pd.read_csv(history)
h=h[(h.season==2026)&(h.week.between(1,5))].copy()
h["weight"]=h.week.map({1:1,2:1.2,3:1.45,4:1.75,5:2.1})
h["weighted_targets"]=h.targets*h.weight
h["weighted_attempts"]=h.team_pass_attempts*h.weight
# Group by stable player ID so abbreviated/full display names don't split history.
shares=h.groupby(["player_id","recent_team"],as_index=False).agg(
    player_name=("player_name","first"),
    target_numerator=("weighted_targets","sum"),
    attempt_denominator=("weighted_attempts","sum"),
    observed_games=("week","nunique"),
    total_targets=("targets","sum"))
shares["share_2026"]=shares.target_numerator/shares.attempt_denominator
import re
def identity(name):
    parts=re.sub(r"[^a-z0-9 ]"," ",str(name).casefold()).split()
    while parts and parts[-1] in {"jr","sr","ii","iii","iv","v"}: parts.pop()
    return parts[0][0]+"_"+parts[-1] if parts else ""
shares["player_key"]=shares.player_name.map(identity)
p["player_key"]=p.Player.map(identity)
# Resolve abbreviated Atlanta RB names using distinct 2026 player IDs.
for pid,key in [("00-0038542","bijan_robinson"),("00-0037746","brian_robinson")]:
    shares.loc[(shares.player_id==pid)&(shares.recent_team=="ATL"),"player_key"]=key
for name,key in [("Bijan Robinson","bijan_robinson"),("Brian Robinson","brian_robinson")]:
    p.loc[(p.Player==name)&(p.Team=="ATL"),"player_key"]=key
# A key like B.Robinson on ATL can refer to two players. Exclude those
# ambiguous keys rather than combining unrelated players.
dupes=shares.duplicated(["player_key","recent_team"],keep=False)
if dupes.any():
    print("Excluded ambiguous historical matches:",shares.loc[dupes,["player_name","recent_team","player_key"]].to_dict("records"))
    shares=shares.loc[~dupes].copy()
qbs=p[p.Position=="QB"].groupby("Team").Pass_Att.sum().to_dict()
p=p.merge(shares[["player_key","recent_team","share_2026","observed_games","total_targets"]],
          how="left",left_on=["player_key","Team"],right_on=["player_key","recent_team"])
p["Target_Share_Status"]=np.where(p.share_2026.notna(),"2026_observed","missing_2026_data")
p["Original_Targets"]=p.Targets
# Apply only observed shares. Do not fabricate a fallback share or apply a 30% cap.
for i,row in p.iterrows():
    if row.Position not in ("WR","TE","RB") or pd.isna(row.share_2026): continue
    attempts=qbs.get(row.Team)
    if not attempts or row.Targets<=0: continue
    new_targets=attempts*row.share_2026
    ratio=new_targets/row.Targets
    for col in ("Targets","Receptions","Rec_Yds","Rec_TD"):
        p.at[i,col]=row[col]*ratio
# Reconcile only over-allocated teams downward. Never inflate player targets
# to consume all QB attempts; unmodeled receivers retain residual opportunity.
p["Team_Pass_Volume_Status"]="within_projected_attempts"
for team, subset in p[p.Position.isin(["WR","TE","RB"])].groupby("Team"):
    qb_attempts=qbs.get(team,0)
    indices=subset.index
    if qb_attempts<=0:
        p.loc[indices,"Team_Pass_Volume_Status"]="missing_projected_qb"
        continue
    total=subset.Targets.sum()
    if total>qb_attempts:
        # Protect primary options: remove excess from the smallest projected
        # target workloads first. Never scale every receiver proportionally.
        excess=total-qb_attempts
        order=sorted(indices,key=lambda i:(p.at[i,"Targets"],p.at[i,"Player"]))
        for idx in order:
            if excess<=1e-9: break
            old_targets=float(p.at[idx,"Targets"])
            if old_targets<=0: continue
            removed=min(old_targets,excess)
            factor=(old_targets-removed)/old_targets
            for col in ("Targets","Receptions","Rec_Yds","Rec_TD"):
                p.at[idx,col]=float(p.at[idx,col])*factor
            p.at[idx,"Team_Pass_Volume_Status"]="reduced_bottom_up"
            excess-=removed
        if excess>1e-6:
            raise ValueError(f"Failed to reconcile {team}: {excess:.3f} targets remain")
# Recalculate receiving contribution, preserving original rushing and passing scoring adjustments.
for i,row in p.iterrows():
    if row.Position not in ("WR","TE","RB"): continue
    old=p.at[i,"Original_Targets"]
    if not old or pd.isna(row.share_2026): continue
    original_rec_yards=row.Rec_Yds/(p.at[i,"Targets"]/old)
    original_rec_td=row.Rec_TD/(p.at[i,"Targets"]/old)
    original_receptions=row.Receptions/(p.at[i,"Targets"]/old)
    delta_std=.1*(p.at[i,"Rec_Yds"]-original_rec_yards)+6*(p.at[i,"Rec_TD"]-original_rec_td)
    delta_rec=p.at[i,"Receptions"]-original_receptions
    p.at[i,"Standard"]=row.Standard+delta_std
    p.at[i,"Half_PPR"]=row.Half_PPR+delta_std+.5*delta_rec
    p.at[i,"PPR"]=row.PPR+delta_std+delta_rec
p.drop(columns=["player_key","recent_team"],inplace=True)
p.to_csv(output,index=False,float_format="%.3f")
print(f"Saved {output}; observed players: {int((p.Target_Share_Status=='2026_observed').sum())}; missing: {int((p.Target_Share_Status=='missing_2026_data').sum())}")
